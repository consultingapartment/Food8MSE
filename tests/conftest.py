"""Жинхэнэ МХБ-ийн тайлангийн бүтцийг (мөрийн дугаар, текст хэлбэрийн тоо, толгой мөр) дуурайсан туршилтын файл."""
from pathlib import Path

import pytest
from openpyxl import Workbook


def make_report(path: Path, assets: float, revenue: float, *, unit: str = "/Мянган төгрөг/",
                end: str | None = "2025.01.01-2025.06.30", scale: float = 1.0, sheets=("СБД", "ОДТ"),
                string_numbers: bool = True) -> Path:
    """Баланс: хөрөнгө = assets, өр = 40%, өмч = 60%. ОДТ: орлого = revenue, өртөг 60%, цэвэр ашиг 10%."""
    a = assets * scale
    num = (lambda v: str(float(v))) if string_numbers else float
    wb = Workbook()
    bs = wb.active
    bs.title = sheets[0]
    bs.append(["Байгууллагын нэр: ТУРШИЛТ"])
    bs.append(["", "САНХҮҮ БАЙДЛЫН ТАЙЛАН"])
    if end:
        bs.append(["", "", "Тайлант үе:", end])
    bs.append(["", "", "", "", unit])
    bs.append(["", "№", "Үзүүлэлт", "Эхний үлдэгдэл", "Эцсийн үлдэгдэл"])
    rows = [
        ("1", "ХӨРӨНГӨ", 0), ("1.1", "Эргэлтийн хөрөнгө", 0),
        ("1.1.1", "Мөнгө,түүнтэй адилтгах хөрөнгө", a * 0.1),
        ("1.1.2", "Дансны авлага", a * 0.2),
        ("1.1.3", "Татвар, НДШ – ийн авлага", a * 0.01),
        ("1.1.6", "Бараа материал", a * 0.19),
        ("1.1.11", "Эргэлтийн хөрөнгийн дүн", a * 0.5),
        ("1.2", "Эргэлтийн бус хөрөнгө", 0),
        ("1.2.1", "Үндсэн хөрөнгө", a * 0.5),
        ("1.2.10", "Эргэлтийн бус хөрөнгийн дүн", a * 0.5),
        ("1.3", "Нийт хөрөнгийн дүн", a),
        ("2", "ӨР ТӨЛБӨР БА ЭЗДИЙН ӨМЧ", 0), ("2.1", "ӨР ТӨЛБӨР", 0),
        ("2.1.1", "БОГИНО ХУГАЦААТ ӨР ТӨЛБӨР", 0),
        ("2.1.1.1", "Дансны өглөг", a * 0.1),
        ("2.1.1.9", "Нөөц  /өр төлбөр/", a * 0.03),
        ("2.1.1.13", "Богино хугацаат өр төлбөрийн дүн", a * 0.3),
        ("2.1.2", "УРТ ХУГАЦААТ ӨР ТӨЛБӨР", 0),
        ("2.1.2.2", "Нөөц /өр төлбөр/", a * 0.01),
        ("2.1.2.6", "Урт хугацаат өр төлбөрийн дүн", a * 0.1),
        ("2.2", "Өр төлбөрийн нийт дүн", a * 0.4),
        ("", "ЭЗДИЙН ӨМЧ", 0),
        ("2.3", "Өмч", a * 0.1),
        ("2.3.2", "-хувийн", a * 0.1),
        ("2.3.9", "Хуримтлагдсан ашиг", a * 0.5),
        ("2.3.13", "Эздийн өмчийн дүн", a * 0.6),
        ("2.4", "Өр төлбөр ба эздийн өмчийн дүн", a),
    ]
    for code, label, v in rows:
        bs.append(["", code, label, num(0), num(v)])
    bs.append(["Захирал ....................... /Ц.Эрдэнэбилэг/"])

    inc = wb.create_sheet(sheets[1])
    inc.append(["Байгууллагын нэр: ТУРШИЛТ"])
    inc.append(["", "ОРЛОГЫН ДЭЛГЭРЭНГҮЙ ТАЙЛАН"])
    inc.append(["", "", "", "", unit])
    inc.append(["", "№", "Үзүүлэлт", "Эхний үлдэгдэл", "Эцсийн үлдэгдэл"])
    r = revenue * scale
    for code, label, v in [
        ("1", "Борлуулалтын орлого (цэвэр)", r), ("2", "Борлуулалтын өртөг", r * 0.6),
        ("3", "Нийт ашиг ( алдагдал)", r * 0.4), ("22", "Татварын дараахь ашиг (алдагдал)", r * 0.1),
        ("24", "Тайлант үеийн цэвэр ашиг ( алдагдал)", r * 0.1),
        ("25", "Бусад дэлгэрэнгүй орлого", r * 0.1),
    ]:
        inc.append(["", code, label, num(9), num(v)])
    wb.create_sheet("ӨӨТ").append(["хамааралгүй sheet"])
    wb.save(path)
    return path


@pytest.fixture
def report_factory():
    return make_report
